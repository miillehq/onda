//! Deterministic TypeScript contract export; CI checks for drift.
use onda_core::{
    contracts::*,
    error::{AppError, ErrorCode},
};
use ts_rs::TS;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let destination =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../ui/src/generated/core.ts");
    let declarations = [
        ErrorCode::decl(&ts_rs::Config::default()),
        AppError::decl(&ts_rs::Config::default()),
        ExecutionPreference::decl(&ts_rs::Config::default()),
        QualityProfile::decl(&ts_rs::Config::default()),
        ThemePreference::decl(&ts_rs::Config::default()),
        TrayIconStyle::decl(&ts_rs::Config::default()),
        AiProvider::decl(&ts_rs::Config::default()),
        PasteShortcut::decl(&ts_rs::Config::default()),
        Shortcut::decl(&ts_rs::Config::default()),
        AppProfile::decl(&ts_rs::Config::default()),
        Settings::decl(&ts_rs::Config::default()),
        EntrySource::decl(&ts_rs::Config::default()),
        DictionaryKind::decl(&ts_rs::Config::default()),
        DictionaryEntry::decl(&ts_rs::Config::default()),
        Snippet::decl(&ts_rs::Config::default()),
        Transform::decl(&ts_rs::Config::default()),
        Phase::decl(&ts_rs::Config::default()),
        OperationMode::decl(&ts_rs::Config::default()),
        DataRoute::decl(&ts_rs::Config::default()),
        OperationState::decl(&ts_rs::Config::default()),
        DailyUsage::decl(&ts_rs::Config::default()),
        UsageSummary::decl(&ts_rs::Config::default()),
        Profile::decl(&ts_rs::Config::default()),
        HistoryEntry::decl(&ts_rs::Config::default()),
        OperationResult::decl(&ts_rs::Config::default()),
        DiffKind::decl(&ts_rs::Config::default()),
        DiffSegment::decl(&ts_rs::Config::default()),
        LearningProposal::decl(&ts_rs::Config::default()),
        SpanMetric::decl(&ts_rs::Config::default()),
        AppEvent::decl(&ts_rs::Config::default()),
    ];
    // Values the development mock must share with Rust, generated so they cannot drift. Both
    // platforms' defaults, so the generated file is the same whichever OS runs the generator.
    let defaults = serde_json::to_string_pretty(&Settings::defaults_for(false))?;
    let macos_defaults = serde_json::to_string_pretty(&Settings::defaults_for(true))?;
    let limits = serde_json::json!({
        "maxHistoryDays": MAX_HISTORY_DAYS,
        "maxRecordingSeconds": MAX_RECORDING_SECONDS,
        "maxProviderSettingBytes": MAX_PROVIDER_SETTING_BYTES,
        "maxNameCharacters": onda_core::profile::MAX_NAME_CHARACTERS,
    });
    let content = format!(
        "// Generated by onda-contracts. Do not edit.\n{}\n\n/** `Settings::default()` on Windows and Linux: what a fresh profile starts with. */\nexport const DEFAULT_SETTINGS: Settings = {defaults};\n\n/** `Settings::default()` on macOS: the same, but Control+Shift+Space dictates. */\nexport const MACOS_DEFAULT_SETTINGS: Settings = {macos_defaults};\n\n/** Limits enforced by `Settings::validate` and the profile. */\nexport const LIMITS = {} as const;\n",
        declarations
            .iter()
            .map(|declaration| format!("export {declaration}"))
            .collect::<Vec<_>>()
            .join("\n"),
        serde_json::to_string_pretty(&limits)?
    );
    if std::env::args().any(|argument| argument == "--check") {
        // A Windows checkout with core.autocrlf has CRLF line endings; only the text matters.
        if std::fs::read_to_string(&destination)?.replace("\r\n", "\n") != content {
            return Err("Generated frontend contracts have drifted; run npm run contracts.".into());
        }
        return Ok(());
    }
    if let Some(parent) = destination.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(destination, content)?;
    Ok(())
}

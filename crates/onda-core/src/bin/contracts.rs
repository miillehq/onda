//! Deterministic TypeScript contract export; CI checks for drift.
use onda_core::{
    contracts::*,
    error::{AppError, ErrorCode},
};
use ts_rs::TS;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let destination =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../ui/src/generated/core.ts");
    let declarations = [
        ErrorCode::decl(&ts_rs::Config::default()),
        AppError::decl(&ts_rs::Config::default()),
        ExecutionPreference::decl(&ts_rs::Config::default()),
        QualityProfile::decl(&ts_rs::Config::default()),
        ThemePreference::decl(&ts_rs::Config::default()),
        PasteShortcut::decl(&ts_rs::Config::default()),
        Shortcut::decl(&ts_rs::Config::default()),
        AppProfile::decl(&ts_rs::Config::default()),
        Settings::decl(&ts_rs::Config::default()),
        EntrySource::decl(&ts_rs::Config::default()),
        DictionaryKind::decl(&ts_rs::Config::default()),
        DictionaryEntry::decl(&ts_rs::Config::default()),
        Snippet::decl(&ts_rs::Config::default()),
        Transform::decl(&ts_rs::Config::default()),
        Phase::decl(&ts_rs::Config::default()),
        OperationMode::decl(&ts_rs::Config::default()),
        DataRoute::decl(&ts_rs::Config::default()),
        OperationState::decl(&ts_rs::Config::default()),
        DailyUsage::decl(&ts_rs::Config::default()),
        HistoryEntry::decl(&ts_rs::Config::default()),
        OperationResult::decl(&ts_rs::Config::default()),
        DiffKind::decl(&ts_rs::Config::default()),
        DiffSegment::decl(&ts_rs::Config::default()),
        LearningProposal::decl(&ts_rs::Config::default()),
        SpanMetric::decl(&ts_rs::Config::default()),
        AppEvent::decl(&ts_rs::Config::default()),
    ];
    let content = format!(
        "// Generated by onda-contracts. Do not edit.\n{}\n",
        declarations
            .iter()
            .map(|declaration| format!("export {declaration}"))
            .collect::<Vec<_>>()
            .join("\n")
    );
    if std::env::args().any(|argument| argument == "--check") {
        if std::fs::read_to_string(&destination)? != content {
            return Err("Generated frontend contracts have drifted; run npm run contracts.".into());
        }
        return Ok(());
    }
    if let Some(parent) = destination.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(destination, content)?;
    Ok(())
}
